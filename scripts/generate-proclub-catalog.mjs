function wa(msg, label = 'whatsapp') {
  return {
    position: 0,
    stepType: 'ACTION',
    actionType: 'SEND_WHATSAPP',
    config: { waPhone: '{memberPhone}', waMessage: msg, label, stepKey: label },
  }
}

function step(actionType, config, label) {
  return { position: 0, stepType: 'ACTION', actionType, config: { ...config, label, stepKey: label } }
}

